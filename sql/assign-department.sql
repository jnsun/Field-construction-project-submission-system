-- --------------------------------------------------------------------------
-- 第 4 步：确认分配结果（重新查询，部门应已显示）
-- --------------------------------------------------------------------------
SELECT
  au.email                                          AS "用户邮箱",
  p.full_name                                       AS "姓名",
  p.role                                            AS "角色",
  COALESCE(d.name, '⚠️ 未分配部门')                  AS "所属部门"
FROM auth.users au
LEFT JOIN public.profiles p     ON p.id = au.id
LEFT JOIN public.departments d  ON d.id = p.department_id
ORDER BY p.role DESC NULLS LAST, au.created_at ASC;

