-- 施工项目月报管理系统 - 账号部门分配脚本
-- ==========================================================================
-- 适用场景：登录提示"您的账号尚未分配部门，请联系管理员分配部门后再登录"
--
-- 说明：
--   1. 先执行【第 1 步】查看所有账号的部门分配情况
--   2. 根据结果执行【第 2 步】为账号分配部门
--   3. 可选：【第 3 步】设置管理员（管理员不需要分配部门）
--   4. 执行【第 4 步】确认分配结果
--
-- 执行方法：Supabase 控制台 -> SQL Editor -> 粘贴 -> Run
-- ==========================================================================

-- --------------------------------------------------------------------------
-- 第 1 步：查看所有账号与部门分配情况（执行后看结果表）
--    重点看"所属部门"为 (空白/NULL) 的账号，以及左侧的用户邮箱
-- --------------------------------------------------------------------------
SELECT
  au.email                                          AS "用户邮箱",
  p.full_name                                       AS "姓名",
  p.role                                            AS "角色",
  COALESCE(d.name, '⚠️ 未分配部门')                  AS "所属部门"
FROM auth.users au
LEFT JOIN public.profiles p     ON p.id = au.id
LEFT JOIN public.departments d  ON d.id = p.department_id
ORDER BY p.role DESC NULLS LAST, au.created_at ASC;

-- --------------------------------------------------------------------------
-- 第 2 步：为账号分配部门
--   👇 把下面两处替换成实际值：
--     ① '你的账号邮箱@example.com'  → 你的登录邮箱
--     ② '工程一部'                  → 该账号所属的部门名称（见下方部门列表）
--   ★ 注意：UPDATE 里的 WHERE 用邮箱匹配，需保证邮箱唯一
-- --------------------------------------------------------------------------
UPDATE public.profiles
SET department_id = (SELECT id FROM public.departments WHERE name = '工程一部')
WHERE email = '你的账号邮箱@example.com';

-- 可用部门名称（共 24 个）：
-- 工程一部/工程二部/工程三部/工程四部/工程五部
-- 市政一部/市政二部
-- 建筑一部/建筑二部/建筑三部
-- 装饰工程部/基础设施部/机电工程部/钢结构部/园林景观部/环保工程部
-- 水利工程部/路桥工程部/隧道工程部/管道工程部/电力工程部/通信工程部
-- 安防工程部/检测中心

-- --------------------------------------------------------------------------
-- 第 3 步（可选）：把某个账号设为管理员
--   管理员账号不需要分配部门，登录后进入管理仪表盘，可查看所有部门报送
-- --------------------------------------------------------------------------
